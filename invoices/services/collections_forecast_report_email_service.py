from dataclasses import dataclass
from datetime import date

from django.conf import settings
from django.template.loader import render_to_string
from django.urls import reverse
from django.utils.translation import gettext as _


def _long_date(d: date) -> str:
    """'September 7, 2026' without relying on the non-portable %-d strftime flag."""
    return f"{d.strftime('%B')} {d.day}, {d.year}"


def _money(value) -> str:
    """'1234.50' -- plain, locale-independent, always two decimals."""
    return f"{value:.2f}"


@dataclass
class CollectionsForecastEmail:
    recipients: list
    subject: str
    body_html: str


class CollectionsForecastReportEmailService:
    """
    Builds the collections-forecast report email from an already-computed
    forecast (see CollectionsForecastService.build_forecast) -- this
    service only turns that data into an email, it never queries the
    database itself, so the numbers always match what the calendar shows.

    "View Invoices" links come straight from the forecast rows
    (row["view_url"], built once by Client.invoices_admin_url) -- this
    service does not build that URL itself, so the calendar, the email,
    and their templates all share one source of truth for it.

    Visual style intentionally matches the client-facing payment reminder
    email (same header color, table styling, footer) so both read as the
    same product to whoever reads them. All display strings are English
    msgids, translated via the project's .po catalogs like everywhere else.
    """

    TEMPLATE = "invoices/email/forecast_report.html"

    TEAL = "#0f766e"
    AMBER = "#b45309"
    TEXT = "#1f2937"

    @classmethod
    def build_email(cls, company, forecast: dict, recipients: list, has_logo: bool = False) -> CollectionsForecastEmail:
        today = forecast.get("today") or date.today()
        subject = _("Collections Forecast — %(company)s — %(date)s") % {
            "company": str(company),
            "date": today.strftime("%d/%m/%Y"),
        }

        sections = []
        if forecast["overdue"]["clients"]:
            sections.append(cls._section_context(
                title=_("Overdue"),
                total=forecast["overdue"]["total"],
                clients=forecast["overdue"]["clients"],
                title_color=cls.AMBER,
            ))

        for bucket in (b for b in forecast["buckets"] if b["count"] > 0):
            sections.append(cls._section_context(
                title=_long_date(bucket["date"]),
                total=bucket["total"],
                clients=bucket["clients"],
                title_color=cls.TEXT,
            ))

        company_email = getattr(company, "email", "") or ""
        company_phone = getattr(company, "phone", "") or ""
        contact_message = None
        if company_email and company_phone:
            contact_message = _("Questions? Email us at %(email)s or call %(phone)s.") % {
                "email": company_email, "phone": company_phone,
            }
        elif company_email:
            contact_message = _("Questions? Email us at %(email)s.") % {"email": company_email}
        elif company_phone:
            contact_message = _("Questions? Call us at %(phone)s.") % {"phone": company_phone}

        date_from = forecast.get("date_from") or today
        date_to = forecast.get("date_to") or today
        range_label = _("%(date_from)s – %(date_to)s") % {
            "date_from": date_from.strftime("%d/%m/%Y"),
            "date_to": date_to.strftime("%d/%m/%Y"),
        }
        base_url = settings.BACKEND_URL.rstrip("/")
        context = {
            "report_title": _("Collections Forecast"),
            "company": str(company),
            "date_label": _long_date(today),
            "intro_text": _(
                "Here is your collections forecast from %(date_from)s to %(date_to)s, "
                "plus everything already overdue:"
            ) % {"date_from": date_from.strftime("%d/%m/%Y"), "date_to": date_to.strftime("%d/%m/%Y")},
            "notice_text": None,
            "kpis": [
                {"label": _("To Collect This Month"), "value": _money(forecast["month_total"]), "color": cls.TEAL},
                {"label": _("Overdue"), "value": _money(forecast["overdue"]["total"]), "color": cls.AMBER},
                {"label": range_label,
                 "value": _money(forecast.get("window_total", 0)), "color": cls.TEXT},
            ],
            "entity_label": _("Client"),
            "sections": sections,
            "empty_text": _("No invoices are due for collection in this range."),
            "cta_url": f"{base_url}{reverse('admin:invoices_salesinvoice_collections_forecast')}",
            "cta_label": _("Open Collections Forecast"),
            "has_logo": has_logo,
            "contact_message": contact_message,
            "footer_text": _("This is an automated internal report generated by our collections system."),
        }

        body_html = render_to_string(cls.TEMPLATE, context)
        return CollectionsForecastEmail(recipients=recipients, subject=subject, body_html=body_html)

    @staticmethod
    def _section_context(title, total, clients, title_color) -> dict:
        return {
            "title": title,
            "title_color": title_color,
            "total": _money(total),
            "rows": [
                {
                    "name": client["client_name"],
                    "day_total": _money(client["day_total"]),
                    "total_owed": _money(client["total_owed"]),
                    "amount_is_link": True,
                    "view_url": client["view_url"],
                }
                for client in clients
            ],
        }
